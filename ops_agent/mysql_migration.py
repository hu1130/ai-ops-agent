@dataclass(frozen=True)
class MysqlExportOptions:
    sqlite_path: Path
    output_path: Path
    database_name: str = ""
    schema_only: bool = False
    data_only: bool = False
    batch_size: int = DEFAULT_BATCH_SIZE


def export_sqlite_to_mysql(options: MysqlExportOptions) -> dict[str, Any]:
    sqlite_path = options.sqlite_path
    if not sqlite_path.exists():
        raise FileNotFoundError(f"SQLite database not found: {sqlite_path}")
    options.output_path.parent.mkdir(parents=True, exist_ok=True)
    connection = sqlite3.connect(sqlite_path)
    connection.row_factory = sqlite3.Row
    try:
        tables = sqlite_tables(connection)
        row_counts = {table: table_row_count(connection, table) for table in tables}
        with options.output_path.open("w", encoding="utf-8", newline="\n") as handle:
            write_mysql_header(handle, options)
            if not options.data_only:
                for table in tables:
                    handle.write(mysql_create_table_sql(connection, table))
                    handle.write("\n")
                for table in tables:
                    for statement in mysql_index_sql(connection, table):
                        handle.write(statement)
                        handle.write("\n")
                handle.write("\n")
            if not options.schema_only:
                handle.write("START TRANSACTION;\n")
                for table in tables:
                    write_mysql_insert_batches(connection, handle, table, options.batch_size)
                handle.write("COMMIT;\n")
            handle.write("SET FOREIGN_KEY_CHECKS=1;\n")
        return {
            "status": "exported",
            "sqlite_path": str(sqlite_path),
            "output_path": str(options.output_path),
            "database_name": options.database_name,
            "tables": tables,
            "row_counts": row_counts,
            "total_rows": sum(row_counts.values()),
            "schema_only": options.schema_only,
            "data_only": options.data_only,
        }
    finally:
        connection.close()


def format_mysql_export_result(result: dict[str, Any]) -> str:
    lines = [
        "MySQL migration export completed.",
        f"- SQLite: {result.get('sqlite_path', '')}",
        f"- Output: {result.get('output_path', '')}",
        f"- Tables: {len(result.get('tables') or [])}",
        f"- Rows: {result.get('total_rows', 0)}",
    ]
    database_name = str(result.get("database_name") or "")
    if database_name:
        lines.append(f"- Database: {database_name}")
    lines.append("")
    lines.append("Table row counts:")
    row_counts = result.get("row_counts") if isinstance(result.get("row_counts"), dict) else {}
    for table in result.get("tables") or []:
        lines.append(f"- {table}: {row_counts.get(table, 0)}")
    return "\n".join(lines)


def sqlite_tables(connection: sqlite3.Connection) -> list[str]:
    rows = connection.execute(
        """
        select name
        from sqlite_master
        where type = 'table'
          and name not like 'sqlite_%'
        order by name
        """
    ).fetchall()
    return [str(row["name"]) for row in rows]


def table_row_count(connection: sqlite3.Connection, table: str) -> int:
    row = connection.execute(f"select count(*) as total from {sqlite_identifier(table)}").fetchone()
    return int(row["total"] if row else 0)


def write_mysql_header(handle: Any, options: MysqlExportOptions) -> None:
    handle.write("-- Generated by ops_agent.mysql_migration. Review before importing into production.\n")
    handle.write("SET NAMES utf8mb4;\n")
    handle.write("SET FOREIGN_KEY_CHECKS=0;\n")
    database_name = options.database_name.strip()
    if database_name:
        handle.write(f"CREATE DATABASE IF NOT EXISTS {mysql_identifier(database_name)} CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;\n")
        handle.write(f"USE {mysql_identifier(database_name)};\n")
    handle.write("\n")


def mysql_create_table_sql(connection: sqlite3.Connection, table: str) -> str:
    columns = sqlite_table_columns(connection, table)
    lines = [f"DROP TABLE IF EXISTS {mysql_identifier(table)};", f"CREATE TABLE {mysql_identifier(table)} ("]
    column_lines = []
    primary_keys = []
    for column in columns:
        name = str(column["name"])
        column_type = mysql_column_type(column)
        nullable = "" if int(column["notnull"] or 0) == 0 or int(column["pk"] or 0) else " NOT NULL"
        default = mysql_column_default(column_type, column["dflt_value"])
        if int(column["pk"] or 0):
            primary_keys.append(name)
        if int(column["pk"] or 0) and name == "id":
            column_lines.append(f"  {mysql_identifier(name)} BIGINT NOT NULL AUTO_INCREMENT")
        else:
            column_lines.append(f"  {mysql_identifier(name)} {column_type}{nullable}{default}")
    if primary_keys:
        joined = ", ".join(mysql_identifier(name) for name in primary_keys)
        column_lines.append(f"  PRIMARY KEY ({joined})")
    lines.append(",\n".join(column_lines))
    lines.append(") ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;")
    return "\n".join(lines)


def sqlite_table_columns(connection: sqlite3.Connection, table: str) -> list[sqlite3.Row]:
    return connection.execute(f"PRAGMA table_info({sqlite_identifier(table)})").fetchall()


def mysql_column_type(column: sqlite3.Row) -> str:
    name = str(column["name"])
    sqlite_type = str(column["type"] or "").lower()
    if name == "id" and int(column["pk"] or 0):
        return "BIGINT"
    if sqlite_type.startswith("integer"):
        if name.startswith(("is_", "has_")) or name in {
            "approval_required",
            "auto_execute",
            "false_positive",
            "verification_required",
        }:
            return "TINYINT"
        return "BIGINT"
    if sqlite_type.startswith("real") or sqlite_type.startswith("double") or sqlite_type.startswith("float"):
        return "DOUBLE"
    if name.endswith("_json") or name in LARGE_TEXT_COLUMNS:
        return "LONGTEXT"
    if name in VARCHAR_COLUMNS or name.endswith("_at") or name.endswith("_by"):
        return "VARCHAR(255)"
    return "LONGTEXT"


def mysql_default(value: Any) -> str:
    if value is None:
        return ""
    text = str(value).strip()
    if not text:
        return ""
    lowered = text.lower()
    if lowered == "null":
        return " DEFAULT NULL"
    if text.startswith("'") and text.endswith("'"):
        return f" DEFAULT {mysql_quote(text[1:-1])}"
    if is_number_literal(text):
        return f" DEFAULT {text}"
    return f" DEFAULT {mysql_quote(text)}"


def mysql_column_default(column_type: str, value: Any) -> str:
    default = mysql_default(value)
    if not default or default == " DEFAULT NULL" or "TEXT" not in column_type.upper():
        return default
    return f" DEFAULT ({default.removeprefix(' DEFAULT ')})"


def is_number_literal(value: str) -> bool:
    try:
        float(value)
    except ValueError:
        return False
    return True


def mysql_index_sql(connection: sqlite3.Connection, table: str) -> list[str]:
    statements: list[str] = []
    for index in connection.execute(f"PRAGMA index_list({sqlite_identifier(table)})").fetchall():
        index_name = str(index["name"])
        if index_name.startswith("sqlite_autoindex"):
            continue
        unique = "UNIQUE " if int(index["unique"] or 0) else ""
        columns = [
            str(row["name"])
            for row in connection.execute(f"PRAGMA index_info({sqlite_identifier(index_name)})").fetchall()
        ]
        if not columns:
            continue
        column_sql = ", ".join(mysql_identifier(column) for column in columns)
        statements.append(
            f"CREATE {unique}INDEX {mysql_identifier(index_name)} ON {mysql_identifier(table)} ({column_sql});"
        )
    return statements


def write_mysql_insert_batches(
    connection: sqlite3.Connection,
    handle: Any,
    table: str,
    batch_size: int,
) -> None:
    columns = [str(column["name"]) for column in sqlite_table_columns(connection, table)]
    if not columns:
        return
    rows = connection.execute(f"select * from {sqlite_identifier(table)} order by {mysql_export_order_column(columns)}").fetchall()
    if not rows:
        return
    batch_size = max(1, int(batch_size or DEFAULT_BATCH_SIZE))
    column_sql = ", ".join(mysql_identifier(column) for column in columns)
    for offset in range(0, len(rows), batch_size):
        batch = rows[offset : offset + batch_size]
        values = []
        for row in batch:
            values.append("(" + ", ".join(mysql_value(row[column]) for column in columns) + ")")
        handle.write(f"INSERT INTO {mysql_identifier(table)} ({column_sql}) VALUES\n")
        handle.write(",\n".join(values))
        handle.write(";\n")


def mysql_export_order_column(columns: list[str]) -> str:
    if "id" in columns:
        return sqlite_identifier("id")
    if "created_at" in columns:
        return sqlite_identifier("created_at")
    return sqlite_identifier(columns[0])


def mysql_value(value: Any) -> str:
    if value is None:
        return "NULL"
    if isinstance(value, bool):
        return "1" if value else "0"
    if isinstance(value, (int, float)):
        return str(value)
    if isinstance(value, (dict, list)):
        return mysql_quote(json.dumps(value, ensure_ascii=False))
    return mysql_quote(str(value))


def mysql_quote(value: str) -> str:
    escaped = (
        value.replace("\\", "\\\\")
        .replace("\0", "\\0")
        .replace("\n", "\\n")
        .replace("\r", "\\r")
        .replace("\x1a", "\\Z")
        .replace("'", "''")
    )
    return f"'{escaped}'"


def mysql_identifier(value: str) -> str:
    return "`" + str(value).replace("`", "``") + "`"


def sqlite_identifier(value: str) -> str:
    return '"' + str(value).replace('"', '""') + '"'
